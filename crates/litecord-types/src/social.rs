/// Bit set of what can be done with a channel. Hand-rolled to avoid a
/// dependency for six flags.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, Serialize, Deserialize)]
#[serde(transparent)]
pub struct ChannelCapabilities(pub u32);

impl ChannelCapabilities {
    pub const DISCOVERABLE: Self = Self(1 << 0);
    pub const READABLE: Self = Self(1 << 1);
    pub const WRITABLE: Self = Self(1 << 2);
    pub const LINKABLE: Self = Self(1 << 3);
    pub const VOICE: Self = Self(1 << 4);
    pub const OPEN_EXTERNAL: Self = Self(1 << 5);

    pub const fn empty() -> Self {
        Self(0)
    }
    pub const fn contains(self, other: Self) -> bool {
        self.0 & other.0 == other.0
    }
    pub const fn union(self, other: Self) -> Self {
        Self(self.0 | other.0)
    }
}

impl std::ops::BitOr for ChannelCapabilities {
    type Output = Self;
    fn bitor(self, rhs: Self) -> Self {
        self.union(rhs)
    }
}

