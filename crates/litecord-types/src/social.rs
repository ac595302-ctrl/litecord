/// A relationship between the current user and another user. The Social SDK
/// distinguishes Discord-wide and game-scoped relationships; both are kept.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Relationship {
    pub user_id: UserId,
    pub discord: RelationshipKind,
    pub game: RelationshipKind,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub since: Option<Timestamp>,
}

impl Relationship {
    pub fn is_friend(&self) -> bool {
        self.discord == RelationshipKind::Friend || self.game == RelationshipKind::Friend
    }
    pub fn is_blocked(&self) -> bool {
        self.discord == RelationshipKind::Blocked || self.game == RelationshipKind::Blocked
    }
}

