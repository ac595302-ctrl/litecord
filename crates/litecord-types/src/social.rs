//! Canonical social state: users, presence, relationships, guilds, channels,
//! conversations, messages, lobbies and voice.
//!
//! These are Litecord's *own* representations. Adapters convert SDK objects
//! into them; nothing here mirrors an SDK layout.

use std::sync::Arc;

use serde::{Deserialize, Serialize};

use crate::ids::*;
use crate::Timestamp;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct User {
    pub id: UserId,
    pub username: Arc<str>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub global_name: Option<Arc<str>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub avatar_url: Option<Arc<str>>,
    #[serde(default)]
    pub is_bot: bool,
    /// Provisional (game-only) accounts created through the Social SDK.
    #[serde(default)]
    pub is_provisional: bool,
}

impl User {
    /// The name a UI should show by default.
    pub fn display_name(&self) -> &str {
        self.global_name.as_deref().unwrap_or(&self.username)
    }
}

