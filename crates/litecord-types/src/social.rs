#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum MessageExtra {
    Attachment {
        filename: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        content_type: Option<String>,
        #[serde(default)]
        size_bytes: u64,
    },
    Embed {
        #[serde(default, skip_serializing_if = "Option::is_none")]
        title: Option<String>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        url: Option<String>,
    },
    Poll,
    VoiceMessage,
    Sticker {
        name: String,
    },
    Thread,
    /// Content the SDK reported but Litecord cannot render. UI should offer
    /// "Open in Discord".
    Unsupported {
        kind: String,
    },
}

