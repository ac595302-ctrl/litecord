/// Local voice session state (V1 §15). Transport is Discord's job.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct VoiceState {
    pub connected: bool,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub lobby_id: Option<LobbyId>,
    pub muted: bool,
    pub deafened: bool,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub input_device: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub output_device: Option<String>,
    pub output_volume: f32,
    pub noise_suppression: bool,
    pub push_to_talk: bool,
    #[serde(default)]
    pub participants: Vec<VoiceParticipant>,
}

impl Default for VoiceState {
    fn default() -> Self {
        Self {
            connected: false,
            lobby_id: None,
            muted: false,
            deafened: false,
            input_device: None,
            output_device: None,
            output_volume: 1.0,
            noise_suppression: true,
            push_to_talk: false,
            participants: Vec::new(),
        }
    }
}

/// Session/connection lifecycle (V1 §5). No UI feature may assume `Ready`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(tag = "state", rename_all = "snake_case")]
pub enum SessionState {
    #[default]
    LoggedOut,
    Authorizing,
    Connecting,
    Hydrating,
    Ready,
    Reconnecting,
    Offline,
    /// Error message is already sanitized (no secrets).
    Error {
        message: String,
    },
}

impl SessionState {
    pub fn is_online(&self) -> bool {
        matches!(self, SessionState::Ready | SessionState::Hydrating)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn message_serialization_roundtrip() {
        let m = Message {
            id: MessageId(10),
            conversation_id: ConversationId(20),
            author_id: UserId(30),
            content: "hello".into(),
            sent_at: Timestamp(1_000),
            edited_at: None,
            reply_to: None,
            extras: vec![MessageExtra::Attachment {
                filename: "a.png".into(),
                content_type: Some("image/png".into()),
                size_bytes: 12,
            }],
        };
        let json = serde_json::to_value(&m).unwrap();
        assert_eq!(json["id"], "10");
        assert_eq!(json["extras"][0]["type"], "attachment");
        let back: Message = serde_json::from_value(json).unwrap();
        assert_eq!(back, m);
    }

    #[test]
    fn str_enums_roundtrip() {
        for k in RelationshipKind::ALL {
            assert_eq!(RelationshipKind::parse(k.as_str()).unwrap(), *k);
        }
        assert_eq!(PresenceStatus::DoNotDisturb.as_str(), "dnd");
        assert_eq!(
            serde_json::to_string(&PresenceStatus::DoNotDisturb).unwrap(),
            "\"dnd\""
        );
    }

    #[test]
    fn channel_capabilities() {
        let c = ChannelCapabilities::DISCOVERABLE | ChannelCapabilities::OPEN_EXTERNAL;
        assert!(c.contains(ChannelCapabilities::DISCOVERABLE));
        assert!(!c.contains(ChannelCapabilities::READABLE));
    }
}
